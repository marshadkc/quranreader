# joined or broken spellings in the source
FIX = {"اورمیں": "اور میں", "اورپر": "اور پر", "اوردن": "اور دن", "اورآل": "اور آل", "اورسے": "اور سے", "اوربیوی": "اور بیوی",
       "اےعورتو": "اے عورتو", "گےپر": "گے پر", "د ن": "دن", "طر ف": "طرف", "ا س": "اس", "حاش۔پاکی": "حاش پاکی"}
PUNCT = re.compile(r"[۔،,!/ۭۚ]")


def ur_to_hi(ur):
    t = ur
    for a, b in FIX.items():
        t = t.replace(a, b)
    out = []
    for tok in t.replace("(", " ( ").replace(")", " ) ").split():
        if tok in "()":
            out.append(tok); continue
        core = PUNCT.sub("", tok)
        if not core:
            continue
        if core not in UR_HI:
            return None
        if UR_HI[core]:
            out.append(UR_HI[core])
    return " ".join(out).replace("( ", "(").replace(" )", ")") or None
